// Package decisions is the read model of the accepted grills: the index gf
// generates in the decisions directory, README.md. gf writes it only
// between stages, never while a stage visit of the branch's work is in
// progress, so no stage's scope check sees it change.
package decisions

import (
	"bytes"
	"errors"
	"fmt"
	"os"
	"path"
	"path/filepath"
	"slices"
	"strings"

	"github.com/jordiSalazarr/go-fast/workflow/domain"
	"github.com/jordiSalazarr/go-fast/workflow/eventlog"
)

// Header starts the index: it is gf's, and rewritten from the event log.
const Header = "<!-- Generated by gf from the accepted grills. Don't edit it: gf rewrites it between stages. -->\n"

// Status values of a work in the index.
const (
	InProgress = "in progress"
	Completed  = "completed"
	Abandoned  = "abandoned"
)

// Row is one accepted grill: the latest accepted grill visit of a work.
type Row struct {
	Date       string // when the owner accepted grill, YYYY-MM-DD (UTC)
	Title      string
	WorkType   string
	Work       string
	Branch     string
	Status     string
	Document   domain.RepoPath // the decision document, or grill's artifact when gf can't read it
	EventModel domain.RepoPath // zero when the work has no accepted event model
	acceptedAt int             // log position, for a stable order
}

// ReadGrill reads a grill visit's structured outcome.
type ReadGrill func(path domain.RepoPath) (domain.Grill, error)

// Rows are the works with an accepted grill, in the order their grills were
// first accepted.
func Rows(history eventlog.History, readGrill ReadGrill) ([]Row, error) {
	works, err := history.Works()
	if err != nil {
		return nil, fmt.Errorf("decisions index: %w", err)
	}
	var rows []Row
	for _, w := range works {
		row, ok, err := rowOf(history, w, readGrill)
		if err != nil {
			return nil, err
		}
		if ok {
			rows = append(rows, row)
		}
	}
	slices.SortStableFunc(rows, func(a, b Row) int { return a.acceptedAt - b.acceptedAt })
	return rows, nil
}

func rowOf(history eventlog.History, w domain.WorkState, readGrill ReadGrill) (Row, bool, error) {
	records := history.Records(eventlog.WorkStream(w.ID()))
	if len(records) == 0 {
		return Row{}, false, nil
	}
	started, ok := records[0].Event.(domain.WorkStarted)
	if !ok {
		return Row{}, false, nil
	}
	row := Row{Title: started.Description.String(), WorkType: started.WorkType.String(), Work: w.ID().String(),
		Branch: started.Branch.String(), Status: InProgress, acceptedAt: -1}
	switch w.(type) {
	case domain.CompletedWork:
		row.Status = Completed
	case domain.AbandonedWork:
		row.Status = Abandoned
	}
	var grill, eventModel domain.Visit
	for _, r := range records {
		entered, ok := r.Event.(domain.StageEntered)
		if !ok || (entered.Stage != domain.StageGrill && entered.Stage != domain.StageEventModelling) {
			continue
		}
		id := domain.AssignmentIDFor(w.ID(), entered.Stage, entered.Visit)
		accepted, ok := acceptance(history, id)
		if !ok {
			continue
		}
		if entered.Stage == domain.StageEventModelling {
			eventModel = entered.Visit
			continue
		}
		grill = entered.Visit
		if row.acceptedAt < 0 {
			row.acceptedAt, row.Date = accepted.Position, accepted.OccurredAt.UTC().Format("2006-01-02")
		}
	}
	if grill == (domain.Visit{}) {
		return Row{}, false, nil
	}
	if eventModel != (domain.Visit{}) {
		row.EventModel = domain.EventModelFor(w.ID(), eventModel)
	}
	row.Document = domain.ArtifactFor(w.ID(), domain.StageGrill, grill)
	if g, err := readGrill(domain.GrillFor(w.ID(), grill)); err == nil && g.DocPath() != (domain.RepoPath{}) {
		row.Document = g.DocPath()
	}
	return row, true, nil
}

// acceptance is the record that accepted an assignment, if it was.
func acceptance(history eventlog.History, id domain.AssignmentID) (eventlog.Recorded, bool) {
	for _, r := range history.Records(eventlog.AssignmentStream(id)) {
		if _, ok := r.Event.(domain.AssignmentAccepted); ok {
			return r, true
		}
	}
	return eventlog.Recorded{}, false
}

// Render is the index of the rows, with links relative to the decisions
// directory.
func Render(dir domain.DecisionsDir, rows []Row) string {
	var b strings.Builder
	b.WriteString(Header)
	b.WriteString("# Decisions\n\nThe plan of every work whose grill the owner approved.\n\n")
	b.WriteString("| Date | Title | Work type | Work | Branch | Status | Decision document | Event model |\n")
	b.WriteString("|---|---|---|---|---|---|---|---|\n")
	for _, r := range rows {
		eventModel := "—"
		if r.EventModel != (domain.RepoPath{}) {
			eventModel = link(dir, r.EventModel)
		}
		fmt.Fprintf(&b, "| %s | %s | %s | %s | %s | %s | %s | %s |\n",
			r.Date, cell(r.Title), r.WorkType, r.Work, cell(r.Branch), r.Status, link(dir, r.Document), eventModel)
	}
	return b.String()
}

func link(dir domain.DecisionsDir, target domain.RepoPath) string {
	rel, err := filepath.Rel(filepath.FromSlash(dir.Path().String()), filepath.FromSlash(target.String()))
	if err != nil {
		rel = "/" + target.String()
	}
	rel = filepath.ToSlash(rel)
	return "[" + cell(path.Base(target.String())) + "](" + rel + ")"
}

func cell(s string) string { return strings.ReplaceAll(strings.ReplaceAll(s, "|", `\|`), "\n", " ") }

// AtBoundary reports whether the branch is between stages: its active work,
// if any, has no stage visit in progress, because the current one is
// accepted or not opened yet. The index changes only then.
func AtBoundary(history eventlog.History, branch domain.Branch) (bool, error) {
	fact, err := history.ActiveWorkOn(branch)
	if err != nil {
		return false, err
	}
	work, err := fact.Work()
	if errors.Is(err, domain.ErrNoActiveWork) {
		return true, nil
	}
	if err != nil {
		return false, err
	}
	state, _, err := history.Assignment(work.CurrentAssignment())
	switch {
	case errors.Is(err, eventlog.ErrStreamNotFound):
		return true, nil
	case err != nil:
		return false, err
	}
	switch state.(type) {
	case domain.Accepted, domain.Cancelled:
		return true, nil
	}
	return false, nil
}

// Refresh rewrites the index at root when the branch is between stages and
// the index would change. It writes nothing while no grill was accepted and
// there is no index yet. It reports whether it wrote.
func Refresh(root string, dir domain.DecisionsDir, history eventlog.History, branch domain.Branch, readGrill ReadGrill) (bool, error) {
	between, err := AtBoundary(history, branch)
	if err != nil || !between {
		return false, err
	}
	rows, err := Rows(history, readGrill)
	if err != nil {
		return false, err
	}
	file := filepath.Join(root, filepath.FromSlash(dir.Index().String()))
	old, err := os.ReadFile(file)
	switch {
	case errors.Is(err, os.ErrNotExist) && len(rows) == 0:
		return false, nil
	case err != nil && !errors.Is(err, os.ErrNotExist):
		return false, fmt.Errorf("decisions index: %w", err)
	}
	content := []byte(Render(dir, rows))
	if bytes.Equal(old, content) {
		return false, nil
	}
	if err := os.MkdirAll(filepath.Dir(file), 0o755); err != nil {
		return false, fmt.Errorf("decisions index: %w", err)
	}
	tmp := file + ".tmp"
	if err := os.WriteFile(tmp, content, 0o644); err != nil {
		return false, fmt.Errorf("decisions index: %w", err)
	}
	if err := os.Rename(tmp, file); err != nil {
		return false, fmt.Errorf("decisions index: %w", err)
	}
	return true, nil
}
